export default function ManualPage() {
  const { role } = useAuth()
  const [open, setOpen] = useState('start')
  const sections = useMemo(() => SECTIONS.filter((s) => !s.roles || s.roles.includes(role)), [role])

  return (
    <div className="grid lg:grid-cols-[220px_1fr] gap-4 items-start">
      <Card className="p-3 lg:sticky lg:top-4">
        <p className="text-[12px] text-faint px-2 mb-1">หัวข้อ</p>
        <nav className="flex lg:flex-col flex-wrap gap-1">
          {[...sections, { id: 'status', title: 'ความหมายของสถานะ' }].map((s) => (
            <a
              key={s.id}
              href={`#${s.id}`}
              onClick={() => setOpen(s.id)}
              className={`px-2 py-1.5 rounded-lg text-[13px] ${open === s.id ? 'bg-brandsoft text-brandink font-medium' : 'text-muted hover:text-ink'}`}
            >
              {s.title}
            </a>
          ))}
        </nav>
      </Card>

      <div className="space-y-3">
        {sections.map((s) => (
          <Card key={s.id} id={s.id} className="p-5 scroll-mt-4">
            <div className="flex flex-wrap items-baseline justify-between gap-2 mb-2">
              <h2 className="font-semibold">{s.title}</h2>
              {s.link && <Link to={s.link[0]} className="text-[12px] text-brand hover:underline">{s.link[1]} →</Link>}
            </div>
            {s.roleTable && (
              <div className="grid sm:grid-cols-3 gap-2 mb-3">
                {Object.values(ROLES).map((r) => (
                  <div key={r.key} className={`rounded-xl border p-3 ${r.key === role ? 'border-brand bg-brandsoft' : 'border-line'}`}>
                    <p className="font-medium text-[13px]">{r.label}{r.key === role && <span className="text-[11px] text-brandink"> (คุณ)</span>}</p>
                    <p className="text-[12px] text-muted mt-0.5">{r.hint}</p>
                  </div>
                ))}
              </div>
            )}
            <ol className="list-decimal pl-5 space-y-1.5 text-[13px] text-ink/90 marker:text-faint">
              {s.steps.map((t) => <li key={t}>{t}</li>)}
            </ol>
          </Card>
        ))}

        <Card id="status" className="p-5 scroll-mt-4">
          <h2 className="font-semibold mb-3">ความหมายของสถานะ</h2>
          <div className="grid sm:grid-cols-2 gap-x-6 gap-y-2">
            {Object.values(STATUS).map((st) => (
              <div key={st.key} className="flex items-start gap-3 text-[13px]">
                <span className="w-44 shrink-0"><StatusPill status={st.key} /></span>
                <span className="text-muted">
                  {st.hint || 'ใช้งานได้ตามปกติ'}
                  {st.counted === false && <span className="text-faint"> · ไม่นับในยอดสาขา</span>}
                </span>
              </div>
            ))}
          </div>
        </Card>
      </div>
    </div>
  )
}
