// สิทธิ์ผู้ใช้ 3 ระดับ (ตาม feedback จาก UAT กับเจ้าหน้าที่สาขา)
//   admin = ผู้ดูแลระบบ: ทำได้ทุกอย่าง รวมถึงลบ ถังขยะ จัดการผู้ใช้/สิทธิ์ ประวัติการเข้าใช้ สำรองข้อมูล
//   staff = เจ้าหน้าที่ (พัสดุ): เพิ่ม/แก้ไข นำเข้า พิมพ์ QR เปิด/ปิดรอบตรวจนับ — แต่ลบไม่ได้
//   user  = ผู้ใช้ปกติ (อาจารย์/บุคลากร): ดูอย่างเดียว + ตรวจของที่ตนถือครอง / ตรวจเมื่อได้เป็นกรรมการ
// กรรมการตรวจนับยังเป็นสิทธิ์รายรอบ ไม่ใช่ role
const ROLES = ["admin", "staff", "user"];
const EDITOR_ROLES = ["admin", "staff"];
const isEditor = (user) => EDITOR_ROLES.includes(user?.role);

module.exports = { ROLES, EDITOR_ROLES, isEditor };
