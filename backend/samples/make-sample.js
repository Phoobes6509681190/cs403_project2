// สร้างไฟล์ samples/sample-import.xlsx — ข้อมูลพิมพ์ตามรูปเอกสารตรวจนับจริง (บร.2 ชั้น 1 ห้อง 107)
// ใช้ทดสอบหน้า Import: node samples/make-sample.js
const XLSX = require("xlsx");
const path = require("path");

const IT = "เทคโนโลยีสารสนเทศเพื่อการเรียนการสอนสำหรับวิชาพื้นฐาน";
const SCREEN = "จอรับภาพชนิดมอเตอร์ไฟฟ้า";
const rows = [
  ["1/80", "ตัดโอน"], ["10/80", "ตัดโอน"], ["11/80", "ตัดโอน"], ["12/80", "ตัดโอน"],
  ["13/80", "ปกติ"], ["14/80", "ตัดโอน"], ["15/80", "ตัดโอน"], ["17/80", "ตัดโอน"],
  ["18/80", "ตัดโอน"], ["19/80", "ตัดโอน"], ["2/80", "ตัดโอน"], ["20/80", "ตัดโอน"],
  ["21/80", "ตัดโอน"], ["22/80", "ตัดโอน"], ["23/80", "ปกติ"]
].map(([n, s]) => [s, `วทท-8พ-57-${n}`, IT, "DELL"]);
rows.push(
  ["ปกติ", "วทท-8พ-56-3/3", SCREEN, ""],
  ["ปกติ", "วทท-8พ-56-2/3", SCREEN, ""],
  ["ตัดโอน", "วทท-8พ-57-24/80", IT, "DELL"],
  ["ตัดโอน", "วทท-8พ-57-25/80", IT, "DELL"],
  ["ตัดโอน", "วทท-8พ-57-26/80", IT, "DELL"],
  ["ปกติ", "วทท-8พ-54-2/2", `${SCREEN} ขนาด 100 นิ้ว`, ""],
  ["ปกติ", "วทท-8พ-54-1/2", `${SCREEN} ขนาด 100 นิ้ว`, ""]
);

const header = ["ตึก/อาคาร", "ชั้น", "ห้อง", "ระบุ สถานที่ใช้งาน", "สภาพ", "รหัสสินทรัพย์อ้างอิง", "ชื่อสินทรัพย์", "ยี่ห้อ"];
const aoa = [
  ["ชุด 1"], // หัวกระดาษแบบไฟล์จริง — ระบบต้องหาแถวหัวตารางเองได้
  header,
  ...rows.map(([status, code, name, brand]) => ["บร.2", 1, 107, "บร.2 ชั้น 1 ห้อง 107", status, code, name, brand])
];

const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(aoa), "Sheet1");
const out = path.join(__dirname, "sample-import.xlsx");
XLSX.writeFile(wb, out);
console.log("สร้างแล้ว:", out, `(${rows.length} แถว)`);
